"""Writes the JvmFuncsFallbacks.c of GraalVM's libjvm for a set of static JDK libraries: a function
that stops the program for every JVM_ function that those libraries call and JvmFuncs.c doesn't
have. It does what JvmFuncsFallbacksBuildTask in GraalVM's mx_substratevm.py does when GraalVM
itself is built.

    jvmfuncs-fallbacks.py JvmFuncs.c out.c lib1.a lib2.a ...

NM names another nm than the Mac's, the one of Android's NDK for libraries of Android, whose
functions have no underscore before their names.
"""
import os, re, subprocess, sys

funcs, out, libraries = sys.argv[1], sys.argv[2], sys.argv[3:]
wanted = set()
for library in libraries:
    for line in subprocess.run([os.environ.get('NM', 'nm'), library], capture_output=True, text=True).stdout.splitlines():
        tokens = line.split()
        if len(tokens) == 2 and tokens[0] == 'U' and tokens[1].lstrip('_').startswith('JVM_'):
            wanted.add(tokens[1].lstrip('_'))
have = set(re.findall(r'JNICALL\s+(JVM_\w+)', open(funcs).read()))
NO_ENV = {'JVM_GC', 'JVM_ActiveProcessorCount', 'JVM_GetInterfaceVersion', 'JVM_GetManagement', 'JVM_IsSupportedJNIVersion',
          'JVM_MaxObjectInspectionAge', 'JVM_NativePath', 'JVM_ReleaseUTF', 'JVM_SupportsCX8', 'JVM_BeforeHalt', 'JVM_Halt',
          'JVM_LoadLibrary', 'JVM_UnloadLibrary', 'JVM_FindLibraryEntry', 'JVM_FindSignal', 'JVM_RaiseSignal', 'JVM_RegisterSignal',
          'JVM_FreeMemory', 'JVM_MaxMemory', 'JVM_TotalMemory', 'JVM_RawMonitorCreate', 'JVM_RawMonitorDestroy',
          'JVM_RawMonitorEnter', 'JVM_RawMonitorExit'}
with open(out, 'w') as f:
    f.write('/* Fallback implementations, generated by jvmfuncs-fallbacks.py */\n\n#include <stdio.h>\n#include <stdlib.h>\n#include <jni.h>\n')
    for name in sorted(wanted - have):
        if name in NO_ENV:
            f.write('\nJNIEXPORT void JNICALL %s() {\n    fprintf(stderr, "%s called:  Unimplemented\\n");\n    abort();\n}\n' % (name, name))
        else:
            f.write('\nJNIEXPORT jobject JNICALL %s(JNIEnv *env) {\n    (*env)->FatalError(env, "%s called:  Unimplemented");\n    return NULL;\n}\n' % (name, name))
print(len(wanted - have), 'fallbacks for', len(wanted), 'functions,', len(wanted & have), 'in JvmFuncs.c')
